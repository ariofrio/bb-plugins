// Regenerates the picker's icon catalog from Hugeicons' published index,
// keeping the categories that describe a project rather than UI chrome, one
// icon per name variant, and only icons the free package actually exports.
// The output is committed so builds and CI never touch the network.
// Usage: npm run build:catalog
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import * as freeIcons from "@hugeicons/core-free-icons";

const INDEX_URL = "https://hugeicons.com/api/icons";

// Hugeicons' own categories, minus the ones that are interface furniture.
const PROJECT_CATEGORIES = [
  "ai",
  "buildings",
  "business",
  "clothing",
  "communications",
  "crypto",
  "date-time",
  "devices",
  "e-commerce",
  "education",
  "energy",
  "files-folders",
  "foods",
  "furnitures",
  "games",
  "git",
  "gym",
  "home",
  "image-camera",
  "kitchen",
  "logistics",
  "logos",
  "maps",
  "medical",
  "notes-tasks",
  "programming",
  "science-technology",
  "security",
  "shapes",
  "space",
  "users",
  "weather",
];

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

function exportName(iconName) {
  return `${iconName
    .split("-")
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join("")}Icon`;
}

/** Hugeicons ships folder-01, folder-02…; keep the lowest-numbered variant. */
function collapseVariants(icons) {
  const best = new Map();
  for (const icon of icons) {
    const stem = icon.name.replace(/-\d+$/, "");
    const variant = Number((/-(\d+)$/.exec(icon.name) ?? [, "0"])[1]);
    const current = best.get(stem);
    if (current === undefined || variant < current.variant) {
      best.set(stem, { icon, variant });
    }
  }
  return [...best.values()].map(({ icon }) => icon);
}

const response = await fetch(INDEX_URL);
if (!response.ok) {
  throw new Error(`Icon index request failed (${response.status})`);
}
const { icons } = await response.json();

const categories = new Set(PROJECT_CATEGORIES);
const catalog = collapseVariants(
  icons.filter(
    (icon) =>
      categories.has(icon.category) && exportName(icon.name) in freeIcons,
  ),
)
  .map((icon) => ({
    name: icon.name,
    export: exportName(icon.name),
    category: icon.category,
    // The index stores tags as one comma-separated string. Names already carry
    // their own words, so keep only the tags that add a synonym.
    tags: [
      ...new Set(
        String(icon.tags ?? "")
          .split(",")
          .map((tag) => tag.trim().toLowerCase())
          .filter(Boolean),
      ),
    ]
      .filter((tag) => !icon.name.split("-").includes(tag))
      .slice(0, 8),
  }))
  .sort((left, right) => left.name.localeCompare(right.name));

const seen = new Set();
for (const entry of catalog) {
  if (seen.has(entry.export)) throw new Error(`duplicate ${entry.export}`);
  seen.add(entry.export);
}

writeFileSync(
  resolve(root, "icon-catalog.json"),
  `${JSON.stringify(catalog, null, 1)}\n`,
);

const imports = catalog.map((entry) => `  ${entry.export},`).join("\n");
const entries = catalog
  .map((entry) => `  ${JSON.stringify(entry.name)}: ${entry.export},`)
  .join("\n");
writeFileSync(
  resolve(root, "icon-catalog.generated.ts"),
  `// Generated by scripts/build-icon-catalog.mjs. Do not edit.
import type { IconSvgElement } from "@hugeicons/react";
import {
${imports}
} from "@hugeicons/core-free-icons";

export const CATALOG_ICONS: Record<string, IconSvgElement> = {
${entries}
};
`,
);

const byCategory = {};
for (const entry of catalog) {
  byCategory[entry.category] = (byCategory[entry.category] ?? 0) + 1;
}
console.log(`Wrote ${catalog.length} icons across ${Object.keys(byCategory).length} categories.`);
